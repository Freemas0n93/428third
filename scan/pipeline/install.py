"""Copy optimized layer GLBs into public/models/building with content-hashed names and
regenerate src/data/modelLayers.ts. usage: python3 -I install.py OPT_DIR REPO_ROOT"""
import sys, os, json, hashlib, re, shutil, glob
opt, repo = sys.argv[1], sys.argv[2]
dst = os.path.join(repo, "public/models/building")
os.makedirs(dst, exist_ok=True)
for old in glob.glob(os.path.join(dst, "*.glb")):
    os.remove(old)
rows = []
for path in sorted(glob.glob(os.path.join(opt, "*.glb"))):
    lid = os.path.splitext(os.path.basename(path))[0]
    data = open(path, "rb").read()
    h = hashlib.sha256(data).hexdigest()[:10]
    name = f"{lid}.{h}.glb"
    shutil.copyfile(path, os.path.join(dst, name))
    log = open(os.path.join(opt, lid + ".log")).read() if os.path.exists(os.path.join(opt, lid + ".log")) else ""
    m = re.search(r"output: .*?\((\d+) triangles.*?(\d+) draw calls", log.replace("\n", " "))
    m2 = re.findall(r"output: mesh primitives \((\d+) triangles", log)
    tris = re.findall(r"\((\d+) triangles, \d+ vertices\); (\d+) draw calls", log)
    t, dc = (int(tris[-1][0]), int(tris[-1][1])) if tris else (0, 0)
    rows.append((lid, name, len(data), t, dc))
lines = ["// Generated by scan/pipeline/install.py — do not edit by hand.",
         "// Optimized building layers (meshopt + KTX2) produced from the v33 corrected export.",
         "export const MODEL_FILES: Record<string, { file: string; bytes: number; tris: number; drawCalls: number }> = {"]
for lid, name, b, t, dc in rows:
    lines.append(f"  '{lid}': {{ file: '{name}', bytes: {b}, tris: {t}, drawCalls: {dc} }},")
lines.append("}")
open(os.path.join(repo, "src/data/modelLayers.ts"), "w").write("\n".join(lines) + "\n")
for r in rows: print(*r)
